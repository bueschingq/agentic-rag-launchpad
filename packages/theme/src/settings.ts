// Non-visual widget settings, and the public config document the widget loads at runtime.
// Shared by the console (which serves it), the database (which stores it) and the widget.

import type { ThemeTokens } from "./tokens.ts";

export interface WidgetSettings {
  nickname?: string;
  welcome?: string;
  starters?: string[];
  placeholder?: string;
  // AI disclosure line under the input.
  disclosure?: string;
  showSources?: boolean;
  feedback?: boolean;
  mode?: "overlay" | "inline";
  poweredBy?: boolean;
  // Shown instead of the chat when the deployment is paused or over budget.
  offlineMessage?: string;
}

// GET {console}/api/public/deployments/{id}/config
export interface PublicWidgetConfig {
  deploymentId: string;
  zone: string;
  kbId: string;
  searchConfig: string;
  theme: ThemeTokens;
  settings: Required<Pick<WidgetSettings, "welcome" | "placeholder" | "disclosure" | "showSources" | "feedback" | "mode" | "poweredBy">> &
    Pick<WidgetSettings, "nickname" | "starters">;
  // false when paused or over budget: render offlineMessage, request no tokens.
  online: boolean;
  offlineMessage: string;
}

// POST {console}/api/public/deployments/{id}/token
export interface PublicTokenResponse {
  token: string;
  // Seconds until expiry. The widget times refreshes from this on its own clock, so a
  // visitor's skewed clock can't make every token look expired.
  expiresIn: number;
  expiresAt: string;
  askUrl: string;
}

export const defaultWidgetSettings: PublicWidgetConfig["settings"] = {
  welcome: "Hi! Ask me anything about this site.",
  placeholder: "Ask a question…",
  disclosure: "Answers are generated by AI from this site's content and may contain mistakes.",
  showSources: true,
  feedback: true,
  mode: "overlay",
  poweredBy: false,
};
